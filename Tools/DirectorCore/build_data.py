#!/usr/bin/env python3
"""Validate curated runtime text and export native authored gates/content."""
import argparse,hashlib,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'../NarrativeCore'))
from director_runtime import TRANSIENT_FACTS
MODES=('Easy','Normal','Hard','Punitive')

def q(s): return 'u8'+json.dumps(s,ensure_ascii=True)
def seq(entries): return '{'+', '.join(q(s) for s in entries)+'}'
def bits(modes):
    assert len(modes) == len(set(modes)), 'Duplicate difficulty in cue/block'
    return sum(1<<MODES.index(m) for m in modes)
def b(value): return 'true' if value else 'false'
def generate():
    files=['runtime_ptbr.json','../NarrativeCore/act12_scenes.json','../NarrativeCore/act35_scenes.json','../NarrativeCore/banter_ptbr.json','../NarrativeCore/variants.json','../NarrativeCore/puzzle_contract.json','../MapCore/hospital_graph.json','../NarrativeCore/fact_lifetimes.json']
    sources=[json.loads((ROOT/f).read_text(encoding='utf-8')) for f in files]
    text,early,late,banter,variants,puzzle,graph,lifetimes=sources
    assert all(s['schema']==1 for s in sources) and text['locale']==banter['locale']=='pt-BR'
    markdown=(ROOT/'../../02_GAME_DESIGN/Narrative/PACOTE_TEXTO_CAMPANHA_V1.md').read_text(encoding='utf-8')
    # Runtime strings are curated separately from production notes. Check their
    # words against the reviewed draft instead of displaying Markdown in-game.
    reviewed=markdown.replace('**','').replace('*','')
    for block in text['blocks']:
        for cue in block['cues']:
            assert not cue.get('text') or cue['text'] in reviewed, f"Runtime line requires source review: {cue['id']}"
    audio_nodes={1:['F2_SECURITY','F2_CAMERAS'],2:['B1_GENERATOR','B1_PUMP'],3:['F1_SECURITY'],4:['F1_RADIO','F1_LOBBY'],5:['F2_CAMERAS','F2_SECURITY'],6:['B1_PUMP'],7:['F2_CAMERAS','F3_EXAMS'],8:['F2_SECURITY','B1_MORGUE']}
    for block in text['blocks']:
        if block['id'].startswith('AUD'): block['nodes']=audio_nodes[int(block['id'][3:])]
    for entry in banter['exchanges']:
        cues=[dict(c,kind='speech',id=f"{entry['id']}:{i}") for i,c in enumerate(entry['lines'])]
        if entry['id'] in ('BAN05','BAN11','BAN32','BAN41'): cues[0]['delivered_fact']='jack_previous_encounter_heard'
        text['blocks'].append({'id':entry['id'],'cues':cues,'modes':entry.get('modes',MODES)})
    revision=hashlib.sha256(json.dumps(sources,sort_keys=True,ensure_ascii=True).encode()+markdown.encode()).hexdigest()
    lines=['// Generated by build_data.py; edit authored JSON/draft and regenerate.','#pragma once','#include "Authoring.h"','namespace thug::director::data {','inline const Catalogue& Content() {','static const Catalogue result = [] { Catalogue d;',f'd.revision = {q(revision)};']
    nodes={n['id'] for n in graph['nodes']}
    assert re.fullmatch(r'[0-9]{6}',puzzle['garage']['code'])
    lines.append(f'd.garageCode = {q(puzzle["garage"]["code"])};')
    for n in graph['nodes']:lines.append(f'd.nodeRoles.emplace({q(n["id"])}, {q(n["role"])});')
    transient=TRANSIENT_FACTS
    lines.append(f'd.transientFacts = {seq(sorted(transient))};')
    known={'joe_identified_thomas_body','joe_verified_batman_record','joe_directly_witnessed_thomas_death','joe_returned_for_harley','joe_ignored_harley_request','bartholomeu_cooperated_n24'}
    for block in text['blocks']:
        known.update(block.get('requires',()))
        for c in block['cues']:
            known.update(c.get('all',()));known.update(c.get('none',()))
            if c.get('delivered_fact'):known.add(c['delivered_fact'])
    for s in early['scenes']+late['scenes']:
        known.update(s.get('facts_any',()))
        if s.get('alternative_fact'):known.add(s['alternative_fact'])
    for s in banter['exchanges']:known.update(s.get('requires_facts',()))
    lines.append(f'd.persistentFacts = {seq(sorted(known-transient))};')
    profiles=[]
    for mode in MODES:
        p=variants['difficulty'][mode]
        profiles.append('{'+', '.join((b(p['thomas']=='confirmed'),b(p['joe_harley']=='reciprocal'),b(p['jack']=='progressive_secret')))+'}')
    lines.append('d.profiles = {{'+', '.join(profiles)+'}};')
    lines.append('d.clueMinimumAct = {'+', '.join(str(variants['jack_secret']['minimum_act'][f'J{i}']) for i in range(1,5))+'};')
    lines.append(f'd.minimumClues = {variants["jack_secret"]["minimum_clues"]};')
    for f in puzzle['garage']['fragments']:lines.append(f'd.journalPairs.emplace({q(f["document"])}, {q(f["pair"])});')
    for dataset,is_late in ((early,False),(late,True)):
        for s in dataset['scenes']:
            assert set(s['anchors'])<=nodes
            fields=[q(s['id']),str(s['act']),seq(s['anchors']),seq(s.get('must_seen',[])),seq(s.get('any_seen',[])),q(s.get('alternative_fact','')),q(s.get('companion','')),seq(s.get('facts_any',[])),str(bits(s.get('difficulty',MODES))),b(is_late),b(s.get('requires_hunter_evidence')),b(s.get('requires_reachable_hunter')),b(s.get('requires_reachable_exit')),b(s.get('requires_visited_area'))]
            lines.append(f'd.scenes.emplace({q(s["id"])}, SceneDefinition{{'+', '.join(fields)+'});')
    for s in banter['exchanges']:
        assert set(s['nodes'])<=nodes
        fields=[q(s['id']),str(s['act']),seq(s['nodes']),seq(s['actors']),seq(s.get('after',[])),seq(s.get('before',[])),seq(s.get('requires_facts',[])),str(bits(s.get('modes',MODES)))]
        lines.append(f'd.banter.emplace({q(s["id"])}, BanterDefinition{{'+', '.join(fields)+'});')
    ids=set();cue_ids=set()
    for block in text['blocks']:
        id=block['id'];assert id not in ids;ids.add(id)
        assert set(block.get('nodes',[]))<=nodes
        fields=[q(id),str(bits(block.get('modes',MODES))),seq(block.get('nodes',[])),seq(block.get('requires',[])),seq(c['id'] for c in block['cues'])]
        lines.append(f'd.blocks.emplace({q(id)}, Block{{'+', '.join(fields)+'});')
        for c in block['cues']:
            assert c['id'] not in cue_ids and c['id'].startswith(id+':');cue_ids.add(c['id'])
            assert c['kind'] in {'speech','gesture','document','recording','epilogue'}
            assert c.get('speaker','') in {'','joe','thomas','harley','bartholomeu','jack','radio','recording'}
            assert c.get('delivered_fact','') not in TRANSIENT_FACTS
            fields=[q(c['id']),q(id),'CueKind::'+c['kind'].capitalize(),q(c.get('speaker','')),q(c.get('text','')),q(c.get('asset','')),str(bits(c.get('modes',MODES))),seq(c.get('all',[])),seq(c.get('none',[])),seq(c.get('actors',[])),q(c.get('delivered_fact',''))]
            lines.append(f'd.cues.emplace({q(c["id"])}, Cue{{'+', '.join(fields)+'});')
    assert {f'N{i:02d}' for i in range(1,35)}-{'N26'} <= ids
    assert {f'DOC{i:02d}' for i in range(1,17)} <= ids and {f'AUD{i:02d}' for i in range(1,9)} <= ids
    lines+=['return d; }();','return result;','}','} // namespace thug::director::data','']
    shared='\n'.join(['// Generated by DirectorCore/build_data.py from fact_lifetimes.json.','#pragma once','#include <set>','#include <string>','namespace thug::save::data {','inline const std::set<std::string>& TransientFacts() {',f'static const std::set<std::string> values = {seq(sorted(transient))};','return values;','}','}',''])
    return '\n'.join(lines),len(cue_ids),shared

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    result,count,shared=generate()
    for target,body in ((ROOT/'DirectorData.generated.h',result),(ROOT/'../SaveCore/NarrativeFacts.generated.h',shared)):
        if args.check: assert target.exists() and target.read_text(encoding='utf-8')==body,'Director data out of date; run build_data.py'
        else:target.write_text(body,encoding='utf-8')
    print(f'DirectorData: authored gates and {count} runtime cues verified (pt-BR)')
