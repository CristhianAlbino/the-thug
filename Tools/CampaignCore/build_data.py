#!/usr/bin/env python3
"""Export authored balance and logical hospital bindings to native C++17 data."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MODES = ("Easy", "Normal", "Hard", "Punitive")
CATEGORIES = {"Weapon", "Ammunition", "Explosive", "Medical", "Utility", "Information"}


def quote(value):
    return json.dumps(value, ensure_ascii=True)


def positive(value):
    return type(value) is int and value > 0


def generate():
    balance = json.loads((ROOT / "../NarrativeCore/balance_initial.json").read_text(encoding="utf-8"))
    authored = json.loads((ROOT / "campaign_initial.json").read_text(encoding="utf-8"))
    graph = json.loads((ROOT / "../MapCore/hospital_graph.json").read_text(encoding="utf-8"))
    assert balance["schema"] == authored["schema"] == graph["schema"] == 1
    assert balance["status"] == authored["status"] == "playtest_hypothesis"
    assert set(balance["modes"]) == set(MODES)
    assert balance["trait_order"] == ["trust", "fear", "stress", "loyalty", "selfPreservation", "relationship"]
    nodes = {n["id"] for n in graph["nodes"]}
    items = {i["id"]: i for i in authored["items"]}
    assert len(items) == len(authored["items"])
    for item in items.values():
        assert item["category"] in CATEGORIES and positive(item["slots"]) and positive(item["max"])
        assert type(item["droppable"]) is bool
    digest = hashlib.sha256(json.dumps([balance, authored, graph], sort_keys=True).encode()).hexdigest()
    lines = ["// Generated by build_data.py; edit JSON sources, then regenerate.",
             "#pragma once", '#include "WorldDefinition.h"', '#include "../CompanionCore/CompanionCore.h"',
             "#include <array>", "#include <stdexcept>", "namespace thug::campaign::data {",
             f'inline constexpr const char* Revision = "{digest}";',
             "struct Profile { int capacity; std::optional<double> dawnSeconds;",
             "  std::array<companion::Traits, 3> companions; std::map<std::string, int> loadout; };",
             "inline std::vector<survival::ItemDefinition> Items() { return {"]
    for item in authored["items"]:
        lines.append(f'  {{{quote(item["id"])}, survival::ItemCategory::{item["category"]}, '
                     f'{item["slots"]}, {item["max"]}, {str(item["droppable"]).lower()}}},')
    lines += ["}; }", "inline Profile For(rules::Difficulty difficulty) {", "switch (difficulty) {"]
    for mode in MODES:
        profile = balance["modes"][mode]
        assert positive(profile["inventory_slots"])
        loadout = profile["starting_loadout"]
        assert all(item in items and positive(count) and count <= items[item]["max"]
                   for item, count in loadout.items())
        used = sum(items[item]["slots"] * count for item, count in loadout.items())
        assert used <= profile["inventory_slots"]
        if mode == "Hard":
            assert loadout == {"rifle": 1, "magazine": 2, "grenade": 1, "smoke": 2}
            assert used == sum(balance["hard_starting_loadout_slots"].values())
        traits = []
        assert set(profile["companions"]) == {"harley", "bartholomeu", "jack"}
        for person in ("harley", "bartholomeu", "jack"):
            values = profile["companions"][person]
            assert len(values) == 6 and all(type(v) is int and 0 <= v <= 100 for v in values)
            traits.append("{" + ", ".join(map(str, values)) + ", 0, false}")
        minutes = profile["dawn_minutes"]
        assert minutes is None or positive(minutes)
        dawn = "std::nullopt" if minutes is None else f"std::optional<double>{{{minutes * 60}}}"
        contents = ", ".join("{" + quote(k) + ", " + str(v) + "}" for k, v in sorted(loadout.items()))
        lines.append(f"case rules::Difficulty::{mode}: return {{{profile['inventory_slots']}, {dawn}, "
                     + "{{" + ", ".join(traits) + "}}, {" + contents + "}};")
    lines += ['default: throw std::invalid_argument("Unknown campaign difficulty");', "}", "}",
              "inline WorldDefinition Hospital() {", "WorldDefinition d;",
              'd.levelId = "hospital_logical_v1";']
    for node in sorted(nodes):
        lines.append(f"d.nodes.insert({quote(node)});")
    objects = {}

    def add_object(id_, type_, state, present=True):
        assert id_ not in objects
        objects[id_] = type_
        lines.append(f'd.objects.push_back({{{quote(id_)}, {quote(type_)}, '
                     f'{{{quote(state)}, {{}}, {{}}, {str(present).lower()}}}}});')

    devices = graph["devices"]
    for circuit in devices["circuits"]:
        assert circuit["at"] in nodes
        add_object(circuit["id"], "circuit", circuit["initial"])
        lines.append(f'd.circuitNodes.emplace({quote(circuit["id"])}, {quote(circuit["at"])});')
    powers = {"manual": "Manual", "needs_power": "RequiresPower", "releases_when_off": "ReleasesWithoutPower"}
    for door in devices["doors"]:
        assert door["a"] in nodes and door["b"] in nodes
        add_object(door["id"], "door", door["initial"])
        fields = ", ".join(quote(door[k]) for k in ("id", "a", "b", "circuit"))
        lines.append(f'd.doors.push_back({{{fields}, world::DoorPower::{powers[door["power"]]}}});')
    for camera in devices["cameras"]:
        assert camera["at"] in nodes and camera["view"] in nodes
        add_object(camera["id"], "camera", camera["initial"])
        fields = ", ".join(quote(camera[k]) for k in ("id", "at", "view", "circuit"))
        lines.append(f'd.cameras.push_back({{{fields}}});')
    for hide in devices["hides"]:
        assert hide["at"] in nodes
        add_object(hide["id"], "hide", hide["initial"])
        lines.append(f'd.hides.push_back({{{quote(hide["id"])}, {quote(hide["at"])}}});')
    for object_ in authored["objects"]:
        add_object(object_["id"], object_["type"], object_["state"])
    for pickup in authored["pickups"]:
        assert pickup["node"] in nodes and pickup["item"] in items and positive(pickup["quantity"])
        assert pickup["quantity"] <= items[pickup["item"]]["max"]
        add_object(pickup["id"], "pickup", "available")

    def requirements(entry):
        pairs = entry.get("requires", [])
        assert all(id_ in objects and state for id_, state in pairs)
        return "{" + ", ".join("{" + quote(id_) + ", " + quote(state) + "}" for id_, state in pairs) + "}"

    def event(entry):
        return f'rules::Event::{entry["event"]}' if "event" in entry else "std::nullopt"

    for pickup in authored["pickups"]:
        fields = ", ".join(quote(pickup[k]) for k in ("id", "node", "item"))
        lines.append(f'd.pickups.push_back({{{fields}, {pickup["quantity"]}, {event(pickup)}, {requirements(pickup)}}});')
    for use in authored["uses"]:
        assert use["node"] in nodes and use["object"] in objects and use["before"] != use["after"]
        if use.get("item"):
            assert use["item"] in items and positive(use["quantity"])
        else:
            assert use.get("quantity", 0) == 0 and not use.get("consume", False)
        fields = ", ".join(quote(use.get(k, "")) for k in ("id", "node", "object", "before", "after", "item"))
        lines.append(f'd.uses.push_back({{{fields}, {use.get("quantity", 0)}, '
                     f'{str(use.get("consume", False)).lower()}, {event(use)}, {requirements(use)}}});')
    for unlock in authored["unlocks"]:
        door = next(d for d in devices["doors"] if d["id"] == unlock["door"])
        assert unlock["node"] in (door["a"], door["b"]) and unlock["item"] in items
        fields = ", ".join(quote(unlock[k]) for k in ("id", "node", "door", "item"))
        lines.append(f'd.unlocks.push_back({{{fields}, 1, false}});')
    for trigger in authored["triggers"]:
        assert trigger["node"] in nodes or trigger["node"] == "*"
        lines.append(f'd.triggers.push_back({{{quote(trigger["id"])}, {quote(trigger["node"])}, '
                     f'{event(trigger)}, {requirements(trigger)}}});')
    if "finale" in authored:
        f = authored["finale"]
        assert all(f[k] in nodes for k in ("confrontation_node", "confrontation_exit", "detonator_node", "collapse_shelter"))
        assert len(f["sites"]) >= 3 and len({s["node"] for s in f["sites"]}) == len(f["sites"])
        lines += ["d.finale = FinaleDefinition{};", "auto& f = *d.finale;"]
        for key, member in (("confrontation_node","confrontationNode"),("confrontation_exit","confrontationExit"),("detonator_node","detonatorNode"),("collapse_shelter","collapseShelter")):
            lines.append(f'f.{member} = {quote(f[key])};')
        for key, member in (("confrontation_seconds","confrontationSeconds"),("opportunity_seconds","opportunitySeconds"),("plant_seconds","plantSeconds"),("collapse_seconds","collapseSeconds"),("minimum_companions","minimumCompanions"),("minimum_trust","minimumTrust")):
            lines.append(f'f.{member} = {f[key]};')
        for site in f["sites"]:
            assert site["node"] in nodes
            add_object(site["id"], "rare_site", "empty")
            lines.append(f'f.sites.push_back({{{quote(site["id"])}, {quote(site["node"])}}});')
        for supply in f["supplies"]:
            assert supply["node"] in nodes and supply["item"] in items and positive(supply["quantity"])
            add_object(supply["id"], "rare_supply", "available")
            lines.append(f'f.supplies.push_back({{{quote(supply["id"])}, {quote(supply["node"])}, {quote(supply["item"])}, {supply["quantity"]}}});')
    for a in authored.get("appearances", []):
        assert a["node"] in nodes
        lines.append('d.appearances.push_back({' + ', '.join(quote(a[k]) for k in ("id","node","block")) + f', {a["modes"]}, {a["minimum_act"]}, {a["tickets"]}' + '});')
    lines += ["return d;", "}", "} // namespace thug::campaign::data", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "CampaignData.generated.h"
    rendered = generate()
    if args.check:
        assert output.exists() and output.read_text(encoding="utf-8") == rendered, "Campaign data out of date; run build_data.py"
        print("CampaignData: balance/loadouts/hospital bindings match native data")
    else:
        output.write_text(rendered, encoding="utf-8")
        print("CampaignData: generated native balance and hospital bindings")
