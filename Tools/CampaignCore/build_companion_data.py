#!/usr/bin/env python3
"""Export authored individual inventories, medical influence and task pacing."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MODES = ('Easy', 'Normal', 'Hard', 'Punitive')
PEOPLE = ('harley', 'bartholomeu', 'jack')
GOALS = ('StayHidden', 'SearchResources', 'HelpJoe', 'ShareRoute', 'EscapeAlone', 'UseJoeAsDistraction')
FIELDS = ('trust', 'fear', 'stress', 'loyalty', 'selfPreservation', 'relationship')


def generate():
    authored = json.loads((ROOT / 'companion_runtime.json').read_text(encoding='utf-8'))
    catalogue = json.loads((ROOT / 'campaign_initial.json').read_text(encoding='utf-8'))
    assert authored['schema'] == catalogue['schema'] == 1
    assert authored['status'] == 'playtest_hypothesis'
    assert set(authored['profiles']) == set(MODES)
    items = {i['id']: i for i in catalogue['items']}
    revision = hashlib.sha256(json.dumps([authored, catalogue], sort_keys=True).encode()).hexdigest()
    lines = ['// Generated by build_companion_data.py; edit authored JSON.', '#pragma once',
             '#include "CompanionRuntime.h"', '#include <stdexcept>', 'namespace thug::campaign::partydata {',
             f'inline constexpr const char* Revision = "{revision}";',
             'inline CompanionProfile For(rules::Difficulty mode) { switch(mode) {']
    for mode in MODES:
        profile = authored['profiles'][mode]
        assert set(profile) == set(PEOPLE)
        capacities, loadouts = [], []
        for name in PEOPLE:
            p = profile[name]
            assert type(p['capacity']) is int and 0 < p['capacity'] <= 100
            capacities.append(str(p['capacity']))
            assert all(k in items and type(v) is int and 0 < v <= items[k]['max'] for k, v in p['loadout'].items())
            assert sum(items[k]['slots'] * v for k, v in p['loadout'].items()) <= p['capacity']
            # Ammo is supplied by the existing trait profile (currently zero).
            assert not any(items[k]['category'] == 'Ammunition' for k in p['loadout'])
            loadouts.append('{' + ', '.join('{' + json.dumps(k) + ', ' + str(v) + '}' for k, v in sorted(p['loadout'].items())) + '}')
        lines.append(f'case rules::Difficulty::{mode}: return {{{{{", ".join(capacities)}}}, {{{{{", ".join(loadouts)}}}}}}};')
    lines += ['default: throw std::invalid_argument("Unknown companion difficulty");', '}}']
    durations = authored['interaction_seconds']
    assert set(durations) == set(GOALS) and all(type(durations[g]) in (int, float) and math.isfinite(durations[g]) and 0 <= durations[g] <= 30 for g in GOALS)
    lines.append('inline constexpr std::array<double, 6> InteractionSeconds = {' + ', '.join(str(durations[g]) for g in GOALS) + '};')
    influences = []
    assert set(authored['joe_medical_help']) == set(PEOPLE)
    for name in PEOPLE:
        p = authored['joe_medical_help'][name]
        assert set(p) == set(FIELDS) and all(type(p[k]) in (int, float) and math.isfinite(p[k]) and -100 <= p[k] <= 100 for k in FIELDS)
        influences.append('{' + ', '.join(str(p[k]) for k in FIELDS) + ', 0}')
    lines.append('inline constexpr std::array<companion::Influence, 3> MedicalHelp = {{' + ', '.join(influences) + '}};')
    lines += ['}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'CompanionData.generated.h'
    body = generate()
    if args.check:
        assert target.exists() and target.read_text(encoding='utf-8') == body, 'Companion data out of date; run build_companion_data.py'
    else:
        target.write_text(body, encoding='utf-8')
    print('CompanionData: four individual profiles, task pacing and medical influence verified')
