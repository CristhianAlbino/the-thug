#!/usr/bin/env python3
"""Generate NarrativeData.inl (the C++ copy of the narrative contract).

The JSON files stay the single source of truth:
  variants.json, act12_scenes.json, act35_scenes.json and ../MapCore/hospital_graph.json.
`python emit_cpp.py` rewrites NarrativeData.inl; `--check` fails when it is stale.
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "NarrativeData.inl"


def load(name):
    return json.loads((ROOT / name).read_text(encoding="utf-8"))


def strings(values):
    return "{" + ", ".join(f'"{v}"' for v in values) + "}"


def flag(value):
    return "true" if value else "false"


def render():
    variants = load("variants.json")
    early = load("act12_scenes.json")["scenes"]
    late = load("act35_scenes.json")["scenes"]
    graph = load("../MapCore/hospital_graph.json")
    lines = [
        "// Generated by Tools/NarrativeCore/emit_cpp.py from the narrative JSON contract.",
        "// Do not edit by hand: change the JSON and run `python Tools/NarrativeCore/emit_cpp.py`.",
        "",
        "static const SceneDef kScenes[] = {",
    ]
    for is_late, scenes in ((False, early), (True, late)):
        for s in scenes:
            lines.append(
                "\t{ \"%s\", %d, %s, %s, %s, \"%s\", \"%s\", %s, %s, %s, %s, %s, %s, %s },"
                % (s["id"], s["act"], strings(s["anchors"]), strings(s.get("must_seen", [])),
                   strings(s.get("any_seen", [])), s.get("alternative_fact", ""), s.get("companion", ""),
                   strings(s.get("facts_any", [])), strings(s.get("difficulty", [])),
                   flag(s.get("requires_hunter_evidence")), flag(s.get("requires_reachable_hunter")),
                   flag(s.get("requires_reachable_exit")), flag(s.get("requires_visited_area")), flag(is_late)))
    lines += ["};", "", "static const NodeDef kNodes[] = {"]
    for n in graph["nodes"]:
        lines.append('\t{ "%s", "%s" },' % (n["id"], n["role"]))
    lines += ["};", "", "// Easy, Normal, Hard, Punitive", "static const Profile kProfiles[] = {"]
    for name in ("Easy", "Normal", "Hard", "Punitive"):
        p = variants["difficulty"][name]
        lines.append("\t{ %s, %s, %s }," % (flag(p["thomas"] == "confirmed"), flag(p["joe_harley"] == "reciprocal"),
                                           flag(p["jack"] == "progressive_secret")))
    secret = variants["jack_secret"]
    lines += ["};", "",
              "static const char* const kJackClues[] = %s;" % strings(secret["clues"]),
              'static const char* const kJackReveal = "%s";' % secret["reveal"],
              'static const char* const kJackLateClue = "%s";' % secret["late_clue"],
              "static const int kJackMinimumClues = %d;" % secret["minimum_clues"],
              "static const std::pair<const char*, int> kJackMinimumAct[] = {%s};" % ", ".join(
                  '{"%s", %d}' % kv for kv in secret["minimum_act"].items()),
              'static const char* const kThomasScene = "%s";' % variants["thomas_reveal"]["scene"],
              'static const char* const kThomasFallback = "%s";' % variants["thomas_reveal"]["fallback"],
              'static const char* const kThomasUnconfirmed = "%s";' % variants["thomas_reveal"]["easy_normal"],
              'static const char* const kThomasJoeKnows = "%s";' % variants["thomas_reveal"]["joe_witnessed"],
              "", "// person, status, asymmetric id, reciprocal id (same unless Harley together)",
              "static const EpilogueDef kEpilogues[] = {"]
    for person, table in variants["epilogues"].items():
        for status in variants["companion_statuses"]:
            entry = table[status]
            a, r = (entry["asymmetric"], entry["reciprocal"]) if isinstance(entry, dict) else (entry, entry)
            lines.append('\t{ "%s", "%s", "%s", "%s" },' % (person, status, a, r))
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("NarrativeData.inl is stale: run python Tools/NarrativeCore/emit_cpp.py")
            return 1
        print("NarrativeData.inl matches the JSON contract")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
